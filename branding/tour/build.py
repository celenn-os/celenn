#!/usr/bin/python3
"""Illustrations of the cosmic-blue tours (build_files/first_steps).

- tour-welcome.svg (600 x 220): the welcome page, the default wallpaper in
  miniature (night sky, Milky Way, the logo glowing in the middle)
- tour-banner.svg (600 x 100): the same sky behind the icon of every other
  page; the tour draws the page's icon over its glowing middle

Written to system_files/usr/share/cosmic-blue. Run from the repository root:
python3 branding/tour/build.py
"""

import pathlib
import random

OUT = pathlib.Path("system_files/usr/share/cosmic-blue")

# Logo blues (branding/logo/build.py) and the dark accent
ORBIT = ("#7fe0ff", "#2f6bff")
ACCENT = "#4f8dff"
MOON = "#e6f3ff"


def defs(width, height):
    return f'''<defs>
<clipPath id="card"><rect width="{width}" height="{height}" rx="16"/></clipPath>
<radialGradient id="sky" cx=".5" cy=".55" r=".75"><stop offset="0" stop-color="#1e3f92"/><stop offset=".45" stop-color="#0f2259"/><stop offset="1" stop-color="#030924"/></radialGradient>
<linearGradient id="milky" x1="0" y1="1" x2="1" y2="0"><stop offset="0" stop-color="#5f86d6" stop-opacity="0"/><stop offset=".5" stop-color="#7aa0e8" stop-opacity=".35"/><stop offset="1" stop-color="#5f86d6" stop-opacity="0"/></linearGradient>
<linearGradient id="orbit" x1="0" y1="1" x2="1" y2="0"><stop offset="0" stop-color="{ORBIT[0]}"/><stop offset="1" stop-color="{ORBIT[1]}"/></linearGradient>
<linearGradient id="planet" x1=".2" y1="1" x2=".8" y2="0"><stop offset="0" stop-color="#cfeeff"/><stop offset=".45" stop-color="#4f98f5"/><stop offset="1" stop-color="#14399e"/></linearGradient>
<filter id="blur" x="-50%" y="-50%" width="200%" height="200%"><feGaussianBlur stdDeviation="14"/></filter>
<filter id="glow" x="-150%" y="-150%" width="400%" height="400%"><feGaussianBlur stdDeviation="5"/></filter>
</defs>'''


def stars(width, height, count, clear, seed):
    """Small stars, none in the `clear` (half width, half height) middle box."""
    rng = random.Random(seed)
    out = []
    for _ in range(count):
        x, y = rng.uniform(6, width - 6), rng.uniform(6, height - 6)
        if abs(x - width / 2) < clear[0] and abs(y - height / 2) < clear[1]:
            continue
        r = rng.choice([0.6, 0.7, 0.8, 0.9, 1.1, 1.3])
        o = rng.choice([0.35, 0.5, 0.6, 0.8, 0.9])
        out.append(f'<circle cx="{x:.1f}" cy="{y:.1f}" r="{r}" opacity="{o}"/>')
    return f'<g fill="{MOON}">{"".join(out)}</g>'


def sky(width, height, milky):
    return (f'<rect width="{width}" height="{height}" fill="url(#sky)"/>'
            f'<path d="{milky}" fill="none" stroke="url(#milky)" stroke-width="70" filter="url(#blur)"/>')


def welcome():
    w, h = 600, 220
    return f'''<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}" viewBox="0 0 {w} {h}">
<!-- Generated by branding/tour/build.py -->
{defs(w, h)}
<g clip-path="url(#card)">
{sky(w, h, "M-40 250C120 150 260 160 360 90S560 -10 660 -30")}
{stars(w, h, 70, (95, 95), 7)}
<g transform="translate(300 110) scale(1.7)">
<circle r="46" fill="{ACCENT}" opacity=".22" filter="url(#blur)"/>
<path d="M30.3 -25.4A40 40 0 1 0 30.3 25.4" fill="none" stroke="{ACCENT}" stroke-width="13" stroke-linecap="round" opacity=".7" filter="url(#glow)"/>
<path d="M30.3 -25.4A40 40 0 1 0 30.3 25.4" fill="none" stroke="url(#orbit)" stroke-width="10" stroke-linecap="round"/>
<circle cx="-2" cy="0" r="15" fill="url(#planet)"/>
<circle cx="40" cy="0" r="8" fill="{MOON}" opacity=".5" filter="url(#glow)"/>
<circle cx="40" cy="0" r="4.8" fill="{MOON}"/>
</g>
</g>
</svg>
'''


def banner():
    w, h = 600, 100
    # The page's icon (64 px) sits in the middle, on a soft glow, between
    # two faint orbits that cross the whole banner
    return f'''<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}" viewBox="0 0 {w} {h}">
<!-- Generated by branding/tour/build.py -->
{defs(w, h)}
<g clip-path="url(#card)">
{sky(w, h, "M-40 130C120 80 260 85 360 45S560 -10 660 -25")}
{stars(w, h, 55, (55, 60), 11)}
<ellipse cx="300" cy="50" rx="230" ry="30" fill="none" stroke="url(#orbit)" stroke-width="1.6" opacity=".45" transform="rotate(-6 300 50)"/>
<ellipse cx="300" cy="50" rx="140" ry="19" fill="none" stroke="url(#orbit)" stroke-width="1.2" opacity=".3" transform="rotate(8 300 50)"/>
<circle cx="300" cy="50" r="46" fill="{ACCENT}" opacity=".35" filter="url(#blur)"/>
<circle cx="527" cy="30" r="3.6" fill="{MOON}"/>
<circle cx="527" cy="30" r="6" fill="{MOON}" opacity=".45" filter="url(#glow)"/>
<circle cx="176" cy="66" r="2.6" fill="{MOON}" opacity=".9"/>
</g>
</svg>
'''


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "tour-welcome.svg").write_text(welcome())
    (OUT / "tour-banner.svg").write_text(banner())


if __name__ == "__main__":
    main()
